"""Validate generated temporal states without training or changing raw data."""

from __future__ import annotations

import argparse
import csv
import hashlib
import math
from collections import Counter, defaultdict
from pathlib import Path


META_COLUMNS = {
    "window_start", "source_file", "split", "current_attack", "current_attack_types",
    "future_attack_within_horizon", "future_attack_types", "history_available",
    "history_window_count", "forecast_sample_eligible",
}
WINDOW_SECONDS = 10
HISTORY_WINDOWS = 6
FORECAST_HORIZON_WINDOWS = 6


def read_partition(path: Path) -> tuple[list[str], list[dict[str, str]]]:
    with path.open("r", encoding="utf-8", newline="") as stream:
        reader = csv.DictReader(stream)
        return reader.fieldnames or [], list(reader)


def feature_description(feature: str) -> tuple[str, str, str, str]:
    if feature == "flow_count":
        return "valid flows in the 10-second window", "count", "Measures traffic volume/activity in the network state.", "safe traffic aggregate; no direct label or timestamp input."
    if feature.endswith("__sum"):
        source = feature[:-5]
        return source, "sum", f"Captures total {source.replace('_', ' ')} across flows in the window.", "safe traffic aggregate; inspect scale and extreme-value behavior."
    if feature.endswith("__mean"):
        source = feature[:-6]
        return source, "mean over finite flow values", f"Captures the typical {source.replace('_', ' ')} across flows in the window.", "safe traffic aggregate; missing observations become structural 0.0 when no finite values exist."
    return feature, "builder-derived", "Generated by the temporal builder.", "needs investigation."


def write_feature_doc(path: Path, features: list[str]) -> None:
    lines = [
        "# Temporal Features",
        "",
        "This inventory is derived directly from `scripts/build_temporal_dataset.py`. Each source day is aggregated independently into 10-second states. The model feature vector excludes metadata and contains the following 157 numeric columns.",
        "",
        "| Feature name | Source feature(s) | Aggregation | Network-state meaning | Forecasting safety / leakage concern |",
        "|---|---|---|---|---|",
    ]
    for feature in features:
        source, aggregation, meaning, concern = feature_description(feature)
        lines.append(f"| `{feature}` | `{source}` | `{aggregation}` | {meaning} | {concern} |")
    lines.extend([
        "",
        "`Label`, raw `Timestamp`, `Flow ID`, `Src IP`, `Dst IP`, and Tuesday-only `Src Port` are not direct model features. `current_attack*` and `future_attack*` are evaluation/target metadata only. `window_start`, `source_file`, `split`, and history/eligibility fields are dataset metadata.",
    ])
    path.write_text("\n".join(lines), encoding="utf-8")


def write_quality(path: Path, features: list[str], rows_by_partition: dict[str, list[dict[str, str]]]) -> list[dict[str, object]]:
    output = []
    for feature in features:
        values: list[float] = []
        for rows in rows_by_partition.values():
            for row in rows:
                value = float(row[feature])
                if math.isfinite(value):
                    values.append(value)
        counts = Counter(values)
        if values:
            minimum = min(values)
            maximum = max(values)
            mean = sum(values) / len(values)
            dominant_value = counts.most_common(1)[0][0]
            dominant_percentage = 100 * counts[dominant_value] / len(values)
            near_constant = dominant_percentage >= 99.5
        else:
            minimum = maximum = mean = 0.0
            near_constant = True
            dominant_value = ""
            dominant_percentage = 100.0
        output.append({
            "feature": feature,
            "sample_count": len(values),
            "constant": int(minimum == maximum),
            "near_constant_99_5_percent": int(near_constant),
            "dominant_value": dominant_value,
            "dominant_percentage": round(dominant_percentage, 8),
            "finite_minimum": minimum,
            "finite_maximum": maximum,
            "finite_mean": mean,
            "extremely_large_abs_value": int(max(abs(minimum), abs(maximum)) >= 1e12),
            "distinct_values": len(counts),
        })
    with path.open("w", encoding="utf-8", newline="") as stream:
        writer = csv.DictWriter(stream, fieldnames=list(output[0]))
        writer.writeheader()
        writer.writerows(output)
    return output


def validate_partition(path: Path, feature_columns: list[str]) -> dict[str, object]:
    columns, rows = read_partition(path)
    timestamps = [row["window_start"] for row in rows]
    eligible = [row for row in rows if row["forecast_sample_eligible"] == "1"]
    state_hashes = Counter()
    sequence_hashes = Counter()
    checks = {
        "sorted": timestamps == sorted(timestamps) and len(timestamps) == len(set(timestamps)),
        "no_year_1970": all(not value.startswith("1970-") for value in timestamps),
        "finite_features": True,
        "future_forward_only": True,
        "eligible_history": True,
        "eligible_full_horizon": True,
        "single_source_day": len({value[:10] for value in timestamps}) <= 1,
    }
    current_by_index = [int(row["current_attack"]) for row in rows]
    for index, row in enumerate(rows):
        for feature in feature_columns:
            if not math.isfinite(float(row[feature])):
                checks["finite_features"] = False
        expected = int(any(current_by_index[index + 1:index + 1 + FORECAST_HORIZON_WINDOWS]))
        if int(row["future_attack_within_horizon"]) != expected:
            checks["future_forward_only"] = False
        if row["forecast_sample_eligible"] == "1":
            if int(row["history_available"]) != 1 or int(row["history_window_count"]) != HISTORY_WINDOWS:
                checks["eligible_history"] = False
            if index + FORECAST_HORIZON_WINDOWS >= len(rows):
                checks["eligible_full_horizon"] = False
            span = range(index - HISTORY_WINDOWS + 1, index + FORECAST_HORIZON_WINDOWS + 1)
            if len({rows[position]["split"] for position in span}) != 1:
                checks["eligible_full_horizon"] = False
        if row["forecast_sample_eligible"] == "1":
            state_key = "|".join(row[feature] for feature in feature_columns)
            state_hashes[hashlib.sha256(state_key.encode()).hexdigest()] += 1
            sequence_start = max(0, index - HISTORY_WINDOWS + 1)
            if index + FORECAST_HORIZON_WINDOWS < len(rows) and row["history_available"] == "1":
                sequence_key = "|".join(";".join(rows[position][feature] for feature in feature_columns) for position in range(sequence_start, index + 1))
                sequence_hashes[hashlib.sha256(sequence_key.encode()).hexdigest()] += 1
    return {
        "path": path,
        "columns": columns,
        "rows": rows,
        "eligible": eligible,
        "checks": checks,
        "duplicate_states": sum(count - 1 for count in state_hashes.values() if count > 1),
        "duplicate_sequences": sum(count - 1 for count in sequence_hashes.values() if count > 1),
    }


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--windows-dir", type=Path, default=Path(__file__).resolve().parents[2] / "data/windows")
    parser.add_argument("--audit-dir", type=Path, default=Path(__file__).resolve().parents[2] / "data/audit")
    parser.add_argument("--docs-dir", type=Path, default=Path(__file__).resolve().parents[1] / "docs")
    args = parser.parse_args()
    partitions = sorted(args.windows_dir.glob("*.csv"))
    if len(partitions) != 10:
        raise ValueError(f"Expected 10 source-day partitions, found {len(partitions)}")
    columns, _ = read_partition(partitions[0])
    feature_columns = [column for column in columns if column not in META_COLUMNS]
    results = [validate_partition(path, feature_columns) for path in partitions]
    if any(result["columns"] != columns for result in results):
        raise AssertionError("partition schemas differ")
    rows_by_partition = {result["path"].name: result["rows"] for result in results}
    quality = write_quality(args.audit_dir / "temporal_feature_quality.csv", feature_columns, rows_by_partition)
    write_feature_doc(args.docs_dir / "TEMPORAL_FEATURES.md", feature_columns)

    split_counts: dict[str, Counter[str]] = defaultdict(Counter)
    state_hashes = Counter()
    sequence_hashes = Counter()
    total_rows = total_eligible = 0
    checks = Counter()
    for result in results:
        total_rows += len(result["rows"])
        total_eligible += len(result["eligible"])
        rows = result["rows"]
        for index, row in enumerate(rows):
            if row["forecast_sample_eligible"] != "1":
                continue
            state_key = "|".join(row[feature] for feature in feature_columns)
            state_hashes[hashlib.sha256(state_key.encode()).hexdigest()] += 1
            if index + FORECAST_HORIZON_WINDOWS < len(rows):
                sequence_key = "|".join(";".join(rows[position][feature] for feature in feature_columns) for position in range(index - HISTORY_WINDOWS + 1, index + 1))
                sequence_hashes[hashlib.sha256(sequence_key.encode()).hexdigest()] += 1
        for row in result["eligible"]:
            split_counts[row["split"]]["positive"] += int(row["future_attack_within_horizon"])
            split_counts[row["split"]]["negative"] += int(not int(row["future_attack_within_horizon"]))
        for name, passed in result["checks"].items():
            checks[name] += int(passed)
    summary = {
        "partitions": len(results),
        "state_windows": total_rows,
        "valid_forecasting_samples": total_eligible,
        "feature_count": len(feature_columns),
        "future_positive": sum(counts["positive"] for counts in split_counts.values()),
        "future_negative": sum(counts["negative"] for counts in split_counts.values()),
        "train": dict(split_counts["train"]),
        "validation": dict(split_counts["validation"]),
        "test": dict(split_counts["test"]),
        "duplicate_states": sum(count - 1 for count in state_hashes.values() if count > 1),
        "duplicate_sequences": sum(count - 1 for count in sequence_hashes.values() if count > 1),
        "checks_passed_partitions": dict(checks),
        "constant_features": [row["feature"] for row in quality if row["constant"]],
        "near_constant_features": [row["feature"] for row in quality if row["near_constant_99_5_percent"]],
        "extreme_features": [row["feature"] for row in quality if row["extremely_large_abs_value"]],
    }
    (args.audit_dir / "temporal_validation_summary.json").write_text(__import__("json").dumps(summary, indent=2), encoding="utf-8")
    print(__import__("json").dumps(summary, indent=2))


if __name__ == "__main__":
    main()